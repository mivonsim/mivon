//! VPD (Value Change Dump Plus, Synopsys) - WAV-02.
//!
//! Writer + reader dengan round-trip eksak di atas model VcdData.
//! VPD adalah superset VCD: menambahkan $comment dan memakai blok
//! $dumpvars untuk snapshot awal. Subset praktis di sini menangani hirarki
//! $scope module, $var, #time, dan nilai scalar (0/1/x/z) maupun binary
//! (b<bits>).
//!
//! Kontrak round-trip: parse_vpd(write_vpd(data)) == data. Writer menulis
//! snapshot awal di $dumpvars DAN seluruh perubahan (termasuk waktu 0) di
//! body; reader mengabaikan isi $dumpvars saat membangun changes (body sudah
//! memuat semua transisi), sehingga tidak ada entri ganda.

use std::collections::HashMap;
use std::fmt::Write as _;

use mivon_core::error::SimError;

use super::data::{hex_to_bin, VcdData, VcdSignal};
use super::util::err;

/// Tulis VcdData ke format VPD.
///
/// id_map memetakan id internal ke kode VPD; bila kosong pakai id asli.
/// Format nilai: scalar (1 karakter) langsung, multi-bit via b<bits>.
pub fn write_vpd(
    out_path: &str,
    timescale: &str,
    signals: &[VcdSignal],
    changes: &[(u64, String, String)],
    id_map: &HashMap<String, String>,
) -> Result<(), SimError> {
    let mut out = String::new();
    writeln!(out, "$date").unwrap();
    writeln!(out, "  mwave").unwrap();
    writeln!(out, "$end").unwrap();
    writeln!(out, "$version").unwrap();
    writeln!(out, "  mivon mwave (VPD)").unwrap();
    writeln!(out, "$end").unwrap();
    writeln!(out, "$comment").unwrap();
    writeln!(out, "  Generated by mivon mwave - VPD subset (WAV-02)").unwrap();
    writeln!(out, "$end").unwrap();
    if !timescale.is_empty() {
        writeln!(out, "$timescale {} $end", timescale).unwrap();
    }

    // Hirarki scope (urutkan stabil sesuai input, mirip write_vcd).
    let mut prev_scope: Option<Vec<String>> = None;
    for sig in signals {
        if prev_scope.as_ref() != Some(&sig.scope) {
            if prev_scope.is_some() {
                writeln!(out, "$upscope $end").unwrap();
            }
            for s in &sig.scope {
                writeln!(out, "$scope module {} $end", s).unwrap();
            }
            prev_scope = Some(sig.scope.clone());
        }
        let id = id_map
            .get(&sig.id)
            .cloned()
            .unwrap_or_else(|| sig.id.clone());
        let range = if sig.width > 1 {
            format!(" [{}:0]", sig.width - 1)
        } else {
            String::new()
        };
        writeln!(out, "$var wire {} {} {}{} $end", sig.width, id, sig.name, range).unwrap();
    }
    if prev_scope.is_some() {
        writeln!(out, "$upscope $end").unwrap();
    }
    writeln!(out, "$enddefinitions $end").unwrap();

    // Snapshot awal: nilai pada waktu 0 per sinyal (atau z bila tak ada).
    let mut initial: HashMap<&str, &str> = HashMap::new();
    for (t, id, val) in changes {
        if *t == 0 {
            initial.entry(id.as_str()).or_insert(val.as_str());
        }
    }
    writeln!(out, "$dumpvars").unwrap();
    for sig in signals {
        let id = id_map
            .get(&sig.id)
            .cloned()
            .unwrap_or_else(|| sig.id.clone());
        let val = initial.get(id.as_str()).copied().unwrap_or("z");
        writeln!(out, "{}", emit_value(val, &id)).unwrap();
    }
    writeln!(out, "$end").unwrap();

    // Body: SELURUH perubahan (termasuk waktu 0) diurutkan per waktu.
    let mut cur: Option<u64> = None;
    for (t, id, val) in changes {
        let mapped = id_map
            .get(id)
            .cloned()
            .unwrap_or_else(|| id.clone());
        if cur != Some(*t) {
            writeln!(out, "#{}", t).unwrap();
            cur = Some(*t);
        }
        writeln!(out, "{}", emit_value(val, &mapped)).unwrap();
    }

    std::fs::write(out_path, out).map_err(|e| err(format!("{}: {}", out_path, e)))?;
    Ok(())
}

/// Emit satu baris nilai VPD: scalar langsung, multi-bit via b<bits>.
fn emit_value(val: &str, id: &str) -> String {
    if val.len() == 1 && matches!(val.as_bytes()[0] as char, '0' | '1' | 'x' | 'z') {
        format!("{}{}", val, id)
    } else {
        format!("b{} {}", val, id)
    }
}

/// Parse file VPD kembali menjadi VcdData.
///
/// Toleran terhadap $comment dan blok $dumpvars ... $end (isinya diabaikan
/// saat membangun changes - body sudah memuat semua transisi).
pub fn parse_vpd(path: &str) -> Result<VcdData, SimError> {
    let src = std::fs::read_to_string(path).map_err(|e| err(format!("{}: {}", path, e)))?;
    let lines: Vec<&str> = src.lines().map(|l| l.trim()).collect();

    let mut signals: Vec<VcdSignal> = Vec::new();
    let mut changes: Vec<(u64, String, String)> = Vec::new();
    let mut timescale = String::new();
    let mut scope: Vec<String> = Vec::new();
    let mut max_time = 0u64;
    let mut in_header = true;
    let mut in_comment = false;
    let mut in_dumpvars = false;
    let mut cur_time = 0u64;

    let mut i = 0usize;
    while i < lines.len() {
        let line = lines[i];

        if in_comment {
            if line == "$end" {
                in_comment = false;
            }
            i += 1;
            continue;
        }

        if in_header {
            if let Some(rest) = line.strip_prefix("$scope") {
                let parts: Vec<&str> = rest.split_whitespace().collect();
                if parts.len() >= 2 {
                    scope.push(parts[1].to_string());
                }
            } else if line.starts_with("$upscope") {
                scope.pop();
            } else if let Some(rest) = line.strip_prefix("$var") {
                let parts: Vec<&str> = rest.split_whitespace().collect();
                if parts.len() >= 4 {
                    let width = parts[1].parse::<usize>().unwrap_or(1);
                    let id = parts[2].to_string();
                    let name = parts[3].to_string();
                    signals.push(VcdSignal {
                        id,
                        name,
                        width,
                        scope: scope.clone(),
                    });
                }
            } else if let Some(rest) = line.strip_prefix("$timescale") {
                // Gabungkan token (tangani "$timescale 1 ns $end" -> "1ns").
                let joined: String = rest
                    .split_whitespace()
                    .filter(|t| *t != "$end")
                    .collect::<Vec<&str>>()
                    .concat();
                timescale = if joined.is_empty() { "1ns".to_string() } else { joined };
            } else if line.starts_with("$comment") {
                in_comment = true;
            } else if line.starts_with("$enddefinitions") {
                in_header = false;
            }
            i += 1;
            continue;
        }

        // Body.
        if in_dumpvars {
            if line == "$end" {
                in_dumpvars = false;
            }
            i += 1;
            continue;
        }
        if line.starts_with("$dumpvars") {
            in_dumpvars = true;
            i += 1;
            continue;
        }
        if let Some(t) = line.strip_prefix('#') {
            cur_time = t.parse::<u64>().unwrap_or(0);
            if cur_time > max_time {
                max_time = cur_time;
            }
            i += 1;
            continue;
        }
        if line.starts_with('$') {
            i += 1;
            continue;
        }
        if let Some(rest) = line.strip_prefix('b') {
            let mut parts = rest.splitn(2, char::is_whitespace);
            let val = parts.next().unwrap_or("").to_string();
            let id = parts.next().unwrap_or("").trim().to_string();
            if !id.is_empty() {
                changes.push((cur_time, id, val));
            }
        } else if let Some(rest) = line.strip_prefix('B') {
            let mut parts = rest.splitn(2, char::is_whitespace);
            let val = parts.next().unwrap_or("").to_string();
            let id = parts.next().unwrap_or("").trim().to_string();
            if !id.is_empty() {
                changes.push((cur_time, id, hex_to_bin(&val)));
            }
        } else if line.len() >= 2 {
            let first = line.as_bytes()[0] as char;
            if matches!(first, '0' | '1' | 'x' | 'z') {
                let id = line[1..].trim().to_string();
                if !id.is_empty() {
                    changes.push((cur_time, id, first.to_string()));
                }
            }
        }
        i += 1;
    }

    if signals.is_empty() {
        return Err(err(format!(
            "{}: bukan file VPD valid (tidak ada $var)",
            path
        )));
    }

    Ok(VcdData {
        timescale,
        signals,
        changes,
        max_time,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp_path(name: &str) -> String {
        let mut p = std::env::temp_dir();
        p.push(format!("mivon_vpd_test_{}_{}", std::process::id(), name));
        p.to_string_lossy().into_owned()
    }

    fn sample(name: &str) -> (String, Vec<VcdSignal>, Vec<(u64, String, String)>) {
        let signals = vec![
            VcdSignal {
                id: "c".to_string(),
                name: "clk".to_string(),
                width: 1,
                scope: vec!["top".to_string()],
            },
            VcdSignal {
                id: "D".to_string(),
                name: "data".to_string(),
                width: 8,
                scope: vec!["top".to_string(), "alu".to_string()],
            },
        ];
        let changes = vec![
            (0, "c".to_string(), "1".to_string()),
            (0, "D".to_string(), "00000000".to_string()),
            (5, "c".to_string(), "0".to_string()),
            (10, "D".to_string(), "10101010".to_string()),
            (15, "c".to_string(), "1".to_string()),
            (20, "D".to_string(), "z".to_string()),
            (25, "c".to_string(), "x".to_string()),
        ];
        // Nama file unik per pemanggil agar test tidak saling menimpa saat
        // dijalankan paralel (cargo test default / nextest).
        (tmp_path(name), signals, changes)
    }

    #[test]
    fn write_then_parse_roundtrip() {
        let (path, signals, changes) = sample("roundtrip.vpd");
        write_vpd(&path, "1ns", &signals, &changes, &HashMap::new()).unwrap();
        let parsed = parse_vpd(&path).unwrap();
        assert_eq!(parsed.signals, signals, "signals harus sama");
        assert_eq!(parsed.changes, changes, "changes harus sama (round-trip eksak)");
        assert_eq!(parsed.timescale, "1ns");
        assert_eq!(parsed.max_time, 25);
        let _ = std::fs::remove_file(&path);
    }

    #[test]
    fn vpd_contains_required_keywords() {
        let (path, signals, changes) = sample("keywords.vpd");
        write_vpd(&path, "1ps", &signals, &changes, &HashMap::new()).unwrap();
        let s = std::fs::read_to_string(&path).unwrap();
        assert!(s.contains("$comment"));
        assert!(s.contains("$dumpvars"));
        assert!(s.contains("$enddefinitions $end"));
        assert!(s.contains("$scope module top $end"));
        assert!(s.contains("$scope module alu $end"));
        assert!(s.contains("$var wire 8 D data [7:0] $end"));
        assert!(s.contains("#0"));
        assert!(s.contains("b10101010 D"));
        let _ = std::fs::remove_file(&path);
    }

    #[test]
    fn id_map_is_applied() {
        let (path, signals, changes) = sample("idmap.vpd");
        let mut map = HashMap::new();
        map.insert("c".to_string(), "a".to_string());
        map.insert("D".to_string(), "b".to_string());
        write_vpd(&path, "1ns", &signals, &changes, &map).unwrap();
        let s = std::fs::read_to_string(&path).unwrap();
        assert!(s.contains("$var wire 1 a clk"));
        assert!(s.contains("$var wire 8 b data"));
        let parsed = parse_vpd(&path).unwrap();
        assert_eq!(parsed.signals[0].id, "a");
        assert_eq!(parsed.signals[1].id, "b");
        let _ = std::fs::remove_file(&path);
    }

    #[test]
    fn timescale_with_space_is_joined() {
        // VPD eksternal legal: "$timescale 1 ns $end" -> "1ns".
        let path = tmp_path("timescale.vpd");
        let signals = vec![VcdSignal {
            id: "c".to_string(),
            name: "clk".to_string(),
            width: 1,
            scope: vec!["top".to_string()],
        }];
        let changes = vec![(0, "c".to_string(), "1".to_string())];
        write_vpd(&path, "1ns", &signals, &changes, &HashMap::new()).unwrap();
        // Tulis ulang dengan spasi untuk mensimulasikan VPD eksternal.
        let s = std::fs::read_to_string(&path).unwrap().replace("$timescale 1ns $end", "$timescale 1 ns $end");
        std::fs::write(&path, s).unwrap();
        let parsed = parse_vpd(&path).unwrap();
        assert_eq!(parsed.timescale, "1ns");
        let _ = std::fs::remove_file(&path);
    }

    #[test]
    fn parse_rejects_non_vpd() {
        let path = tmp_path("bad.vpd");
        std::fs::write(&path, "ini bukan vpd
hanya teks acak").unwrap();
        let res = parse_vpd(&path);
        assert!(res.is_err(), "file tanpa $var harus ditolak");
        let _ = std::fs::remove_file(&path);
    }
}
